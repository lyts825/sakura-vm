import { readFile, readdir, writeFile } from 'node:fs/promises';
import ts from 'typescript';

const classes = new Map<string, { keys: Set<string>; base?: string }>();
for (const name of (await readdir('server', { recursive: true }))
  .filter((name) => name.endsWith('.ts'))
  .sort()) {
  const file = 'server/' + name.replaceAll('\\', '/');
  const source = ts.createSourceFile(file, await readFile(file, 'utf8'), ts.ScriptTarget.Latest, true);
  function visit(node: ts.Node) {
    if (ts.isClassDeclaration(node) && node.name) {
      if (classes.has(node.name.text)) throw new Error('Duplicate service class: ' + node.name.text);
      const keys = new Set<string>();
      const privateMember = (member: ts.Node) =>
        ts.canHaveModifiers(member) &&
        ts
          .getModifiers(member)
          ?.some((modifier) =>
            [
              ts.SyntaxKind.PrivateKeyword,
              ts.SyntaxKind.ProtectedKeyword,
              ts.SyntaxKind.StaticKeyword,
            ].includes(modifier.kind),
          );
      for (const member of node.members) {
        if (ts.isConstructorDeclaration(member)) {
          for (const parameter of member.parameters)
            if (parameter.modifiers?.length && !privateMember(parameter) && ts.isIdentifier(parameter.name))
              keys.add(parameter.name.text);
        } else if (
          member.name &&
          !ts.isPrivateIdentifier(member.name) &&
          !privateMember(member) &&
          (ts.isIdentifier(member.name) || ts.isStringLiteral(member.name))
        )
          keys.add(member.name.text);
      }
      const base = node.heritageClauses
        ?.find((clause) => clause.token === ts.SyntaxKind.ExtendsKeyword)
        ?.types[0]?.expression.getText(source);
      classes.set(node.name.text, { keys, base });
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
}
function members(name: string): string[] {
  const entry = classes.get(name)!;
  return [
    ...new Set([...entry.keys, ...(entry.base && classes.has(entry.base) ? members(entry.base) : [])]),
  ].sort();
}
const content =
  '// Generated by scripts/service-contracts.ts. Public members only; checked before release.\n' +
  'export const PUBLIC_SERVICE_MEMBERS: Readonly<Record<string, readonly string[]>> = ' +
  JSON.stringify(
    Object.fromEntries([...classes.keys()].sort().map((name) => [name, members(name)])),
    null,
    2,
  ) +
  ';\n';
const target = 'server/public-service-members.ts';
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8').catch(() => '')) !== content)
    throw new Error('Public service contracts are stale: npx tsx scripts/service-contracts.ts');
} else await writeFile(target, content);
console.log(`Verified public contracts for ${classes.size} service classes.`);
