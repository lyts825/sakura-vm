/** 从插件和整合包目录生成静态清单与服务懒加载表，稳定排序并支持 --check 检查同步状态。
 * Generate stable-sorted static plugin/pack catalogs and lazy server loaders, supporting --check for synchronization. */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath,pathToFileURL } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
/** 将已验证目录 ID 的连字符转下划线，以形成稳定 TS 导入绑定名。
 * Replace hyphens in validated directory IDs with underscores for stable TS import bindings. */
const identifier = (id: string) => id.replace(/-/g, '_');
/** 仅列出真实目录并按名字排序，防止 filesystem 枚举顺序影响生成输出。
 * List directory entries only and sort names so filesystem enumeration cannot change generated output. */
const directories = async (parent: string) =>
  (await readdir(parent, { withFileTypes: true }))
    .filter((item) => item.isDirectory())
    .map((item) => item.name)
    .sort();

/** check 模式逐字比较现有产物并报告同步命令；写入模式更新指定生成文件。
 * Compare existing bytes and report the sync command in check mode, or write the designated generated file. */
async function writeOrCheck(path: string, content: string, check: boolean) {
  if (check) {
    const existing = await readFile(path, 'utf8').catch(() => '');
    if (existing !== content) throw new Error(`插件目录未同步：${path}；运行 npm run plugins:sync`);
  } else await writeFile(path, content);
}

/** 核实插件都有 manifest/server 入口，再稳定生成共享静态目录与按 ID 固定动态导入表；check 不写文件。
 * Require each plugin’s manifest/server entries and stably emit catalog/fixed-ID loaders; check mode writes nothing. */
export async function syncPluginCatalog(check = false) {
  const ids = (await directories(join(root, 'plugins'))).filter((id) => id !== 'packs');
  const packs = (await readdir(join(root, 'plugins', 'packs')))
      .filter((name) => name.endsWith('.ts'))
      .map((name) => name.slice(0, -3))
      .sort();
  for (const id of ids) {
    const files = await readdir(join(root, 'plugins', id));
    if (!files.includes('manifest.ts') || !files.includes('server.ts'))
      throw new Error(`插件缺少 manifest.ts 或 server.ts：${id}`);
  }
  const catalog = [
    '// Generated by scripts/sync-plugin-catalog.ts. Do not edit directly.',
    '// 插件及整合包静态目录：按稳定顺序聚合 manifest，供客户端与服务端共用声明元数据。',
    '// Static plugin/pack catalog: aggregate manifests in stable order for shared client/server declaration metadata.',
    ...ids.map((id) => `import { manifest as ${identifier(id)} } from '../plugins/${id}/manifest.ts';`),
    ...packs.map((id) => `import { pack as pack_${identifier(id)} } from '../plugins/packs/${id}.ts';`),
    "import type { PluginManifest, PluginPack } from './plugin-protocol.ts';",
    '/** 已发现插件与整合包的静态声明，保持稳定顺序；启用状态由运行时配置决定。 / Static declarations of discovered plugins/packs in stable order; runtime configuration owns enablement. */',
    `export const PLUGINS: PluginManifest[] = [${ids.map(identifier).join(', ')}];`,
    `export const PLUGIN_PACKS: PluginPack[] = [${packs.map((id) => `pack_${identifier(id)}`).join(', ')}];`,
    '',
  ].join('\n');
  const loaders = [
    '// Generated by scripts/sync-plugin-catalog.ts. Do not edit directly.',
    '// 服务端插件懒加载表：将已发现的插件 ID 绑定到其服务模块，供插件运行时按需装载。',
    '// Server plugin loaders: bind discovered IDs to their service modules for runtime on-demand loading.',
    "import type { PluginModule } from '../plugin-api.ts';",
    '/** 每个无参 loader 返回对应服务模块的 Promise；动态导入失败会拒绝，调用者负责生命周期/启用检查，装载不等于启用。 / Each zero-argument loader resolves its service module; import failures reject, and callers own lifecycle/enablement checks. Loading alone does not enable a plugin. */',
    'export const loaders: Record<string, () => Promise<PluginModule>> = {',
    ...ids.map((id) => `  /** 按需加载 ${id} 的固定服务入口，无外部路径参数。 / Load the fixed ${id} service entry on demand, with no external path input. */\n  '${id}': () => import('../../plugins/${id}/server.ts'),`),
    '};',
    '',
  ].join('\n');
  await writeOrCheck(join(root, 'shared', 'plugin-catalog.generated.ts'), catalog, check);
  await writeOrCheck(join(root, 'server', 'plugins', 'loaders.generated.ts'), loaders, check);
  const surfaces=await Promise.all(ids.map(async id=>{
    const {manifest}=await import(pathToFileURL(join(root,'plugins',id,'manifest.ts')).href);
    const {pages,tabs,developmentSections,http}=manifest.contributes;
    return {id:manifest.id,name:manifest.name,contributes:{pages,tabs,developmentSections,http}};
  }));
  await writeOrCheck(join(root,'shared','plugin-surfaces.generated.ts'),"/** 由 scripts/sync-plugin-catalog.ts 生成的界面及请求归属投影。 */\nimport type {PluginSurface} from './plugin-surface-queries.ts';\nexport const PLUGIN_SURFACES:PluginSurface[]="+JSON.stringify(surfaces,null,2)+';\n',check);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await syncPluginCatalog(process.argv.includes('--check'));
