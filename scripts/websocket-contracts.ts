/** 从操作目录生成 WebSocket 客户端消息类型、路径元数据及协议说明，拒绝不可支持的 wire 形状。 */
import { readFile, writeFile } from 'node:fs/promises';
import { z } from 'zod';
import { operationEntries } from '../server/operation-catalog.ts';
import { socketChannels, socketCloseReasons } from '../shared/contracts/websocket.ts';
import { requireWireShape, schemaTypeRegistry } from './json-schema-types.ts';

const checking = process.argv.includes('--check');
const entries = operationEntries.filter(entry => entry.declaration.method === 'UPGRADE');
const channels = entries.map(entry => entry.declaration.socketChannel);
if (entries.length !== socketChannels.length || new Set(channels).size !== socketChannels.length ||
    socketChannels.some(channel => !channels.includes(channel)))
  throw new Error('WebSocket contracts must cover each supported channel exactly once');
const types = schemaTypeRegistry();
const routes: Record<string, unknown> = {}, protocols: Record<string, unknown> = {};
function messageNames(schema: any): string[] {
  if (schema === false || schema?.not && Object.keys(schema.not).length === 0) return [];
  if (schema?.oneOf || schema?.anyOf) return (schema.oneOf || schema.anyOf).flatMap(messageNames);
  const name = schema?.properties?.type?.const;
  if (schema?.type !== 'object' || typeof name !== 'string' || !schema.required?.includes('type'))
    throw new Error('JSON socket message must have a required type discriminator');
  return [name];
}
const map = entries.map(entry => {
  const { declaration, socketContract: contract, requestContract: request } = entry;
  const channel = declaration.socketChannel!;
  if (!contract || !request || declaration.contract !== 'declared' || entry.status !== 101 ||
      declaration.transport !== 'websocket' || request.kind !== 'none' || request.required)
    throw new Error('Incomplete WebSocket declaration: ' + declaration.id);
  const roles = [...new Set(['owner', ...contract.authentication.accountRoles])].sort();
  if (JSON.stringify(roles) !== JSON.stringify([...declaration.roles].sort()))
    throw new Error('WebSocket account/local roles differ from admission: ' + channel);
  const query = z.toJSONSchema(request.query, { io: 'input' });
  const headers = z.toJSONSchema(request.headers, { io: 'input' });
  requireWireShape(query, channel + '/query');
  requireWireShape(headers, channel + '/headers');
  const binary = contract.encoding === 'binary';
  if (binary ? contract.framing !== 'byte-stream' || !contract.rfb || contract.clientSchema || contract.serverSchema
    : contract.framing !== 'message' || contract.rfb || !contract.clientSchema || !contract.serverSchema)
    throw new Error('WebSocket framing/schema mismatch: ' + channel);
  if (!binary) {
    requireWireShape(contract.clientSchema, channel + '/client');
    requireWireShape(contract.serverSchema, channel + '/server');
    for (const direction of ['client', 'server'] as const) {
      const names = messageNames(contract[direction + 'Schema' as 'clientSchema' | 'serverSchema']);
      const declared = contract[direction + 'Messages' as 'clientMessages' | 'serverMessages'];
      if (new Set(names).size !== names.length || JSON.stringify(names.sort()) !== JSON.stringify([...declared].sort()))
        throw new Error('WebSocket message direction/discriminators drifted: ' + channel + '/' + direction);
    }
  }
  const parameters = [...declaration.path.matchAll(/\{([^}]+)\}/g)]
    .map(match => JSON.stringify(match[1]) + ': string');
  routes[channel] = { operationId: declaration.id, path: declaration.path, encoding: contract.encoding };
  protocols[channel] = { operation: declaration, query, headers,
    closeFrames: Object.fromEntries(contract.lifecycle.closeReasons.map(reason => [reason, socketCloseReasons[reason]])) };
  return '  ' + JSON.stringify(channel) + ': { operationId: ' + JSON.stringify(declaration.id) +
    '; path: ' + (parameters.length ? '{ ' + parameters.join('; ') + ' }' : 'Record<string, never>') +
    '; query: ' + types.add(query) + '; headers: ' + types.add(headers) +
    '; client: ' + (binary ? 'Uint8Array' : types.add(contract.clientSchema)) +
    '; server: ' + (binary ? 'Uint8Array' : types.add(contract.serverSchema)) + ' };';
}).join('\n');
const typeSource = types.source();
if (/\b(?:unknown|any)\b/.test(typeSource.replace(/"(?:\\.|[^"\\])*"/g, '')))
  throw new Error('WebSocket wire types contain an unsupported schema');
const content = '// Generated by scripts/websocket-contracts.ts. Do not edit directly.\n' +
  '// WebSocket 客户端契约：统一通道参数、双向消息类型和路由；二进制通道按有序 RFB 字节流传输。\n' +
  '// Binary values are ordered RFB stream fragments; read-only JSON client messages are never.\n' +
  typeSource + '\n\nexport type SocketContractMap = {\n' + map + '\n};\n' +
  'export type SocketChannel = keyof SocketContractMap;\n' +
  ['Path', 'Query', 'Headers', 'ClientMessage', 'ServerMessage'].map((name, index) =>
    'export type Socket' + name + '<C extends SocketChannel> = SocketContractMap[C][' +
    JSON.stringify(['path', 'query', 'headers', 'client', 'server'][index]) + '];').join('\n') + '\n' +
  'export const socketRoutes = ' + JSON.stringify(routes, null, 2) + ' as const;\n';
for (const [path, text] of [
  ['../shared/contracts/websocket-client.generated.ts', content],
  ['../docs/schemas/websockets.json', JSON.stringify(protocols, null, 2) + '\n'],
] as const) {
  const file = new URL(path, import.meta.url);
  if (checking) {
    if ((await readFile(file, 'utf8')).replaceAll('\r\n', '\n') !== text)
      throw new Error('WebSocket contracts are stale: ' + path + '; run npm run plugins:schema');
  } else await writeFile(file, text);
}
console.log('WebSocket contracts: ' + entries.length + ' declared, 0 partial; ' + (checking ? 'verified' : 'generated') + '.');
